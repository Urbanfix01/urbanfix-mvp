// Package existing canonical thumbnails; never download private published images.
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const root = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const web = path.resolve(process.env.URBANFIX_WEB_ROOT || path.join(root, '../..'));
const { MATERIALS_CATALOG } = await import(pathToFileURL(path.join(web, 'src/lib/materialsCatalog.js')));
const assets = path.join(root, 'apps/mobile/assets/material-renders'), output = path.join(root, 'apps/mobile/src/materials');
await mkdir(assets, { recursive: true }); await mkdir(output, { recursive: true });
const catalog = [], imports = [], hashes = {};
for (const item of MATERIALS_CATALOG) {
  const filename = `${item.id}.webp`, source = path.join(web, 'public/material-thumbnails', filename);
  const bytes = await readFile(source);
  await copyFile(source, path.join(assets, filename));
  hashes[item.id] = createHash('sha256').update(bytes).digest('hex');
  imports.push(`  ${JSON.stringify(item.id)}: require('../../assets/material-renders/${filename}'),`);
  catalog.push({ id: item.id, name: item.name });
}
await writeFile(path.join(output, 'materialPreviews.ts'), `// Generated by scripts/sync-material-previews.mjs. Do not edit.\nimport type { ImageSourcePropType } from 'react-native';\nexport const materialPreviews: Record<string, ImageSourcePropType> = {\n${imports.join('\n')}\n};\n`);
await writeFile(path.join(output, 'materialRenderCatalog.json'), JSON.stringify(catalog, null, 2) + '\n');
await writeFile(path.join(output, 'materialPreviewManifest.json'), JSON.stringify({ inputs: hashes }, null, 2) + '\n');
console.log(JSON.stringify({ packagedPreviews: catalog.length }));
